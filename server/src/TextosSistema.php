    /** Idioma de quien lee (Accept-Language que manda el juego; sin cabecera, español). */
    public static function idiomaLector(): string
    {
        return CorreoPlantillas::idiomaDeCabecera((string) ($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? ''));
    }

    /** Texto de una plantilla en un idioma (si falta, el español; si tampoco está, la clave), con sus marcadores. */
    public static function texto(string $clave, string $idioma, array $v = []): string
    {
        $L = isset(self::T[$idioma]) ? $idioma : 'es';
        $t = self::T[$L][$clave] ?? self::T['es'][$clave] ?? $clave;
        return self::rellenar($t, $L, $v);
    }

    /** La plantilla en los 10 idiomas: [idioma => texto]. */
    public static function todos(string $clave, array $v = []): array
    {
        $o = [];
        foreach (self::IDIOMAS as $L) $o[$L] = self::texto($clave, $L, $v);
        return $o;
    }

    /** Título y cuerpo del buzón en los 10 idiomas: [idioma => ['titulo' => .., 'cuerpo' => ..]] (para $op['textos']). */
    public static function buzon(string $claveTitulo, string $claveCuerpo, array $v = []): array
    {
        $o = [];
        foreach (self::IDIOMAS as $L) $o[$L] = ['titulo' => self::texto($claveTitulo, $L, $v), 'cuerpo' => self::texto($claveCuerpo, $L, $v)];
        return $o;
    }

    /** Nombre de NOMBRES (mes, liga_semanal, liga_festival) en un idioma; null si no hay (el que llama usa el español). */
    public static function nombre(string $grupo, int|string $k, string $idioma): ?string
    {
        return self::NOMBRES[$idioma][$grupo][$k] ?? null;
    }

    /** Número con el separador de miles del idioma (1.500 / 1,500 / 1 500). */
    public static function numero(int|float $n, string $idioma): string
    {
        $sep = match ($idioma) { 'en', 'zh-CN' => ',', 'fr', 'ru' => ' ', default => '.' };
        return number_format((float) $n, 0, '', $sep);
    }

    /** Fecha corta en el formato del idioma. */
    public static function fecha(int $ts, string $idioma): string
    {
        return match ($idioma) { 'en' => date('M j, Y', $ts), 'de', 'ru', 'tr' => date('d.m.Y', $ts), 'zh-CN' => date('Y年n月j日', $ts), default => date('d/m/Y', $ts) };
    }

    /** Marcadores {..} de un texto (sin repetir, ordenados; {br} no cuenta). @return list<string> */
    public static function marcadores(string $t): array
    {
        preg_match_all('/\{(\w+)\}/', $t, $m);
        $o = array_values(array_unique(array_diff($m[1], ['br'])));
        sort($o);
        return $o;
    }

    private static function rellenar(string $t, string $L, array $v): string
    {
        $r = preg_replace_callback('/\{(\w+)\}/', function ($m) use ($L, $v): string {
            if ($m[1] === 'br') return "\n";
            if (!array_key_exists($m[1], $v)) return $m[0];
            $x = $v[$m[1]];
            if ($x instanceof \Closure) $x = $x($L);
            elseif (is_array($x)) $x = $x[$L] ?? $x['es'] ?? '';
            return (string) $x;
        }, $t);
        return $r ?? $t;
    }
}
